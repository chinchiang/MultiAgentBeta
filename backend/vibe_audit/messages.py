_COMPILED = [(re.compile(pattern, re.S), template) for pattern, template in PATTERNS]


def _part(text):
    """A value inside a message: a status or a known message reads in Chinese, anything else stays as it is."""
    return STATUS_ZH.get(text) or zh(text) or text


def zh(text):
    """The Chinese wording of an English message, or None when the message has no entry."""
    if not isinstance(text, str):
        return None
    if text in ZH:
        return ZH[text]
    for pattern, template in _COMPILED:
        match = pattern.fullmatch(text)
        if match:
            # A group that is itself a known message or status (for example a wrapped reason) is shown in Chinese too.
            return template.format(*(_part(group) for group in match.groups()))
    # "<label>: <message>": a known label, or a known message or status, on either side of the first colon.
    label, colon, rest = text.partition(": ")
    if colon and (label in ZH or rest in STATUS_ZH or zh(rest) is not None):
        return f"{ZH.get(label, label)}：{_part(rest)}"
    return None
